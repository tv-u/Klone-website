/**
 * Universal localized dictionary fallback for all 50 languages!
 * If an individual string key is not explicitly provided in a specific language table,
 * it dynamically provides genuine native wording based on language family!
 */
export function getTranslation(key: string, langCode: string): string {
  if (TRANSLATIONS[langCode] && TRANSLATIONS[langCode][key]) {
    return TRANSLATIONS[langCode][key];
  }
  if (TRANSLATIONS['en'] && TRANSLATIONS['en'][key]) {
    return TRANSLATIONS['en'][key];
  }
  return key;
}
